"""Generate the source inventory: data/manifest.json and data/MANIFEST.md.

Both are derived from what is on disk, so they cannot drift from the data:
  - provenance (origin, licence, generator / URL) from data/sources.json
  - size, SHA-256, line and row counts from the files themselves
  - whether each document is indexed, and its chunk count, from
    data/processed/chunks.jsonl (run `rsa ingest` first)

Fails if any raw file has no provenance entry.

Usage:  uv run python scripts/generate_manifest.py
"""

from __future__ import annotations

import csv
import hashlib
import json
import sys
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
REGISTRY = ROOT / "data" / "sources.json"
CHUNKS = ROOT / "data" / "processed" / "chunks.jsonl"
OUT_JSON = ROOT / "data" / "manifest.json"
OUT_MD = ROOT / "data" / "MANIFEST.md"

FORMAT_NAMES = {"md": "Markdown", "html": "HTML", "pdf": "PDF", "xml": "XML",
                "csv": "CSV", "json": "JSON"}


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _lines(path: Path) -> int | None:
    try:
        with path.open(encoding="utf-8") as f:
            return sum(1 for _ in f)
    except UnicodeDecodeError:
        return None


def _rows(path: Path) -> int | None:
    if path.suffix == ".csv":
        with path.open(encoding="utf-8", newline="") as f:
            return sum(1 for _ in csv.DictReader(f))
    if path.suffix == ".json":
        data = json.loads(path.read_text(encoding="utf-8"))
        return len(data) if isinstance(data, list) else None
    return None


def build() -> dict:
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))["sources"]
    chunk_counts: Counter[str] = Counter()
    if CHUNKS.exists():
        with CHUNKS.open(encoding="utf-8") as f:
            for line in f:
                chunk_counts[json.loads(line)["source_file"]] += 1

    sources, missing = [], []
    for path in sorted(p for p in RAW.rglob("*") if p.is_file()):
        rel = str(path.relative_to(RAW))
        prov = registry.get(rel)
        if prov is None:
            missing.append(rel)
            continue
        entry = {
            "file": rel,
            "format": path.suffix.lstrip("."),
            "size_bytes": path.stat().st_size,
            "sha256": _sha256(path),
            **{k: v for k, v in prov.items() if k not in ("sha256", "format")},
        }
        if prov.get("sha256") and prov["sha256"] != entry["sha256"]:
            entry["sha256_mismatch"] = True
        if (n := _lines(path)) is not None:
            entry["lines"] = n
        if (n := _rows(path)) is not None:
            entry["rows"] = n
        if rel.startswith("policies/"):
            entry["indexed"] = path.name in chunk_counts
            entry["chunks"] = chunk_counts.get(path.name, 0)
            if not entry["indexed"] and prov.get("derived_from") is None:
                entry["note"] = "Not indexed: source of the PDF edition, excluded to avoid duplicate chunks"
        sources.append(entry)

    if missing:
        sys.exit("No provenance entry in data/sources.json for: " + ", ".join(missing))

    policies = [s for s in sources if s["file"].startswith("policies/")]
    indexed = [s for s in policies if s["indexed"]]
    return {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "generator": "scripts/generate_manifest.py",
        "totals": {
            "files": len(sources),
            "policy_files": len(policies),
            "indexed_documents": len(indexed),
            "chunks": sum(chunk_counts.values()),
            "public_files": sum(1 for s in sources if s["origin"] == "public"),
            "synthetic_files": sum(1 for s in sources if s["origin"] == "synthetic"),
            "formats": dict(Counter(s["format"] for s in sources)),
        },
        "sources": sources,
    }


def render_md(m: dict) -> str:
    t = m["totals"]
    by = {s["file"]: s for s in m["sources"]}
    out = [
        "# Data Manifest",
        "",
        f"_Generated by `{m['generator']}` at {m['generated_at']} — do not edit by hand._",
        "",
        f"**{t['files']} files** ({t['public_files']} public, {t['synthetic_files']} synthetic) · "
        f"**{t['indexed_documents']} documents indexed** into **{t['chunks']} chunks** · formats: "
        + ", ".join(f"{FORMAT_NAMES.get(k, k)} ×{v}" for k, v in sorted(t["formats"].items())),
        "",
        "Provenance for every file lives in `data/sources.json`. Synthetic files are also "
        "labelled in-document (`[SYNTHETIC DOCUMENT]` header, `<meta name=\"synthetic\">`, "
        "or a `synthetic` column/field).",
        "",
        "## Public sources",
        "",
        "| File | Publisher | Version | Licence | SHA-256 | Chunks |",
        "|---|---|---|---|---|---|",
    ]
    for s in m["sources"]:
        if s["origin"] == "public":
            out.append(f"| `{s['file']}` | {s['publisher']} ([source]({s['landing_page']})) | "
                       f"{s['version_date']} | {s['license']} | `{s['sha256'][:16]}` | {s['chunks']} |")
    out += ["", "Re-fetch or verify with `uv run python scripts/fetch_public_sources.py [--check]`.",
            "", "## Synthetic policy documents", "",
            "| File | Format | Indexed | Chunks | Lineage |", "|---|---|---|---|---|"]
    for s in m["sources"]:
        if s["origin"] == "synthetic" and s["file"].startswith("policies/"):
            if s.get("derived_from"):
                lineage = f"PDF edition of `{s['derived_from']}`"
            elif not s["indexed"]:
                lineage = "Source of the PDF edition (not indexed, avoids duplicates)"
            else:
                lineage = "Hand-authored synthetic policy"
            out.append(f"| `{s['file']}` | {FORMAT_NAMES[s['format']]} | "
                       f"{'yes' if s['indexed'] else 'no'} | {s['chunks']} | {lineage} |")
    out += ["", "## Synthetic operational records", "",
            "| File | Format | Rows | Generator |", "|---|---|---|---|"]
    for s in m["sources"]:
        if s["file"].startswith("operational/"):
            out.append(f"| `{s['file']}` | {FORMAT_NAMES[s['format']]} | {s.get('rows', '')} | "
                       f"`{s['generator']}` |")
    out += ["", "## Derived artifacts", "",
            "| Path | Produced by |", "|---|---|",
            f"| `data/processed/chunks.jsonl` | `rsa ingest` ({t['chunks']} chunks, each with "
            "`source_file`, `origin`, `synthetic`, `license`, section heading) |",
            "| `data/processed/ingestion_summary.json` | `rsa ingest` |",
            "| `data/vectorstore/qdrant/` | `rsa index` (dense BGE-small + sparse BM25) |",
            "| Operational database | `rsa ingest` (PostgreSQL via `RSA_DATABASE_URL`) |"]
    if any(s.get("sha256_mismatch") for s in by.values()):
        out += ["", "> **Warning:** a public file differs from its registered hash."]
    return "\n".join(out) + "\n"


def main() -> None:
    m = build()
    OUT_JSON.write_text(json.dumps(m, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    OUT_MD.write_text(render_md(m), encoding="utf-8")
    print(json.dumps(m["totals"], indent=2))


if __name__ == "__main__":
    main()
